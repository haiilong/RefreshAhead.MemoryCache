using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace RefreshAhead.MemoryCache.SourceGenerator;

/// <summary>
/// Finds concrete <c>IRefreshAheadMemoryCache&lt;TSnapshot&gt;</c> implementations and emits an AOT-safe
/// <c>AddRefreshAheadMemoryCaches()</c> registration extension into the consuming assembly.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class RefreshAheadMemoryCacheGenerator : IIncrementalGenerator
{
    private const string CacheInterfaceNamespace = "RefreshAhead.MemoryCache";
    private const string CacheInterfaceName = "IRefreshAheadMemoryCache";

    private static readonly SymbolDisplayFormat FullyQualifiedTypeFormat = new(
        globalNamespaceStyle: SymbolDisplayGlobalNamespaceStyle.Included,
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions:
            SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers |
            SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var cacheTypes = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => IsCandidateClass(node),
                transform: static (ctx, _) => GetCacheRegistrationOrNull(ctx))
            .Where(static registration => registration is not null)
            .Select(static (registration, _) => registration!)
            .Collect();

        context.RegisterSourceOutput(cacheTypes, Emit);
    }

    private static bool IsCandidateClass(SyntaxNode node)
    {
        if (node is not ClassDeclarationSyntax classDeclaration)
        {
            return false;
        }

        if (classDeclaration.BaseList is null || classDeclaration.BaseList.Types.Count == 0)
        {
            return false;
        }

        return classDeclaration.Modifiers.All(modifier => modifier.ValueText != "abstract");
    }

    private static CacheRegistration? GetCacheRegistrationOrNull(GeneratorSyntaxContext context)
    {
        var classDeclaration = (ClassDeclarationSyntax)context.Node;
        if (context.SemanticModel.GetDeclaredSymbol(classDeclaration) is not INamedTypeSymbol symbol)
        {
            return null;
        }

        if (symbol.IsAbstract || symbol.IsStatic || symbol.IsGenericType)
        {
            return null;
        }

        if (symbol.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal))
        {
            return null;
        }

        var cacheInterface = symbol.AllInterfaces.FirstOrDefault(IsRefreshAheadMemoryCacheInterface);
        if (cacheInterface is null)
        {
            return null;
        }

        return new CacheRegistration(
            symbol.Name,
            symbol.ToDisplayString(FullyQualifiedTypeFormat),
            cacheInterface.TypeArguments[0].ToDisplayString(FullyQualifiedTypeFormat));
    }

    private static bool IsRefreshAheadMemoryCacheInterface(INamedTypeSymbol candidate)
    {
        var definition = candidate.OriginalDefinition;
        return definition.Name == CacheInterfaceName
            && definition.ContainingNamespace.ToDisplayString() == CacheInterfaceNamespace
            && definition.TypeArguments.Length == 1;
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<CacheRegistration> cacheRegistrations)
    {
        var distinct = cacheRegistrations
            .GroupBy(static registration => registration.CacheTypeFullName + "|" + registration.SnapshotTypeFullName)
            .Select(static group => group.First())
            .OrderBy(static registration => registration.CacheTypeFullName, StringComparer.Ordinal)
            .ToList();

        if (distinct.Count == 0)
        {
            return;
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine();
        builder.AppendLine("namespace RefreshAhead.MemoryCache;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>Source-generated, trimming- and AOT-safe registration for every refresh-ahead memory cache discovered in the compilation.</summary>");
        builder.AppendLine("[System.CodeDom.Compiler.GeneratedCode(\"RefreshAhead.MemoryCache.SourceGenerator\", \"1.0.0\")]");
        builder.AppendLine("internal static class RefreshAheadMemoryCacheGeneratedRegistration");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Registers every concrete <see cref=\"IRefreshAheadMemoryCache{TSnapshot}\"/> implementation discovered by the source generator.");
        builder.AppendLine("    /// Trimming- and NativeAOT-safe (no runtime assembly scanning).");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    internal static IServiceCollection AddRefreshAheadMemoryCaches(this IServiceCollection services)");
        builder.AppendLine("    {");
        builder.AppendLine("        return services.AddRefreshAheadMemoryCaches(refresh =>");
        builder.AppendLine("        {");

        foreach (var registration in distinct)
        {
            builder.AppendLine(
                $"            refresh.Add<{registration.CacheTypeFullName}, {registration.SnapshotTypeFullName}>(name: {ToStringLiteral(registration.JobName)});");
        }

        builder.AppendLine("        });");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        context.AddSource("RefreshAheadMemoryCacheGeneratedRegistration.g.cs", builder.ToString());
    }

    private sealed class CacheRegistration(string jobName, string cacheTypeFullName, string snapshotTypeFullName)
    {
        public string JobName { get; } = jobName;

        public string CacheTypeFullName { get; } = cacheTypeFullName;

        public string SnapshotTypeFullName { get; } = snapshotTypeFullName;
    }

    private static string ToStringLiteral(string value) =>
        "\"" + value.Replace("\\", @"\\").Replace("\"", "\\\"") + "\"";
}
